@pytest.fixture
def client(settings) -> TestClient:
    with TestClient(create_app(settings, FakeProvider())) as c:
        yield c


def signup(client: TestClient, email: str, org: str = "Org", password: str = "password123") -> dict:
    res = client.post(
        "/api/auth/signup", json={"email": email, "password": password, "organization_name": org}
    )
    assert res.status_code == 201, res.text
    return {"Authorization": f"Bearer {res.json()['access_token']}"}


def upload(client: TestClient, headers: dict, path: Path):
    with path.open("rb") as fh:
        return client.post(
            "/api/invoices", headers=headers, files={"file": (path.name, fh, "application/pdf")}
        )
